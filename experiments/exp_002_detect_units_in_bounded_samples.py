import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from crowdmath2026.rationals import fraction_to_str, fraction_sort_key
from crowdmath2026.semirings import generate_n0_q
from crowdmath2026.units import (
    theoretical_units_n0q,
    classify_units_in_sample,
    compare_units_to_theory,
)
from crowdmath2026.experiments import (
    ensure_dir,
    write_json,
    write_csv_rows,
    write_markdown_summary,
)

OUTPUT_DIR = Path(__file__).resolve().parent / "results" / "exp_002_outputs"

BOUNDED_WARNING = (
    "This is a bounded computational sample. It does not prove the full unit "
    "group or any infinite mathematical property."
)

MAX_DEGREE = 5
MAX_COEFF = 3
MAX_ABS_UNIT_EXPONENT = 5

N0Q_CASES: list[tuple[str, Fraction]] = [
    ("2", Fraction(2)),
    ("1_2", Fraction(1, 2)),
    ("1_6", Fraction(1, 6)),
    ("3_2", Fraction(3, 2)),
    ("2_3", Fraction(2, 3)),
    ("4_9", Fraction(4, 9)),
    ("5_3", Fraction(5, 3)),
]


def _theoretical_case_label(q: Fraction) -> str:
    a, b = q.numerator, q.denominator
    if b == 1:
        return "integer"
    if a == 1:
        return "reciprocal_integer"
    return "mixed_fraction"


def _interpretation(
    q: Fraction,
    sample_unit_count: int,
    theoretical_unit_count: int,
    true_positives: int,
    false_positives: int,
    missed: int,
) -> str:
    case = _theoretical_case_label(q)
    q_str = fraction_to_str(q)
    if case == "integer":
        return (
            f"q={q_str}: theory predicts only unit {{1}}. "
            f"Sample found {sample_unit_count} unit(s). "
            "Consistent with UFM multiplicative behavior."
        )
    if case == "reciprocal_integer":
        from crowdmath2026.units import prime_factors
        primes = sorted(prime_factors(q.denominator))
        return (
            f"q={q_str}: theory predicts units generated by primes {primes} dividing {q.denominator}. "
            f"Sample found {sample_unit_count} unit(s), theory (bounded) predicts "
            f"{theoretical_unit_count}. "
            f"True positives: {true_positives}, missed: {missed}. "
            "Missed units have inverses outside the bounded sample."
        )
    return (
        f"q={q_str}: theory (Exercise 1.7) predicts only unit {{1}}. "
        f"Sample found {sample_unit_count} unit(s). "
        "Consistent with mixed-fraction non-UFM multiplicative case."
    )


def run_case(q: Fraction) -> dict[str, object]:
    generation = generate_n0_q(q, MAX_DEGREE, MAX_COEFF)
    zero = Fraction(0)
    nonzero_sample: set[Fraction] = {x for x in generation.keys() if x != zero}

    all_classifications = classify_units_in_sample(nonzero_sample)
    sample_units: set[Fraction] = {
        x for x, inv in all_classifications.items() if inv is not None
    }

    theoretical = theoretical_units_n0q(q, MAX_ABS_UNIT_EXPONENT)
    theoretical_in_pos = {x for x in theoretical if x > zero}

    comparison = compare_units_to_theory(sample_units, theoretical_in_pos)

    label = fraction_to_str(q).replace("/", "_")
    sorted_elements = sorted(nonzero_sample, key=fraction_sort_key)

    csv_rows: list[dict[str, str]] = []
    for val in sorted_elements:
        inv = all_classifications[val]
        is_unit = inv is not None
        is_theoretical = val in theoretical_in_pos

        if is_unit:
            classification = "unit_in_sample"
        else:
            classification = "nonunit_in_sample"

        if is_unit and not is_theoretical:
            notes = (
                "Sample unit not in theoretical unit set within degree bound. "
                "This is a false positive: the inverse appears in the sample "
                "but the element is not a theoretical unit."
            )
        elif not is_unit and is_theoretical:
            notes = (
                "Theoretical unit whose inverse was not found in bounded sample. "
                "False negative caused by sample boundary."
            )
        elif is_unit:
            notes = BOUNDED_WARNING
        else:
            notes = BOUNDED_WARNING

        csv_rows.append(
            {
                "element": fraction_to_str(val),
                "decimal_approx": f"{float(val):.8f}",
                "inverse_in_sample": fraction_to_str(inv) if inv is not None else "",
                "sample_classification": classification,
                "theoretical_unit_within_bound": "yes" if is_theoretical else "no",
                "notes": notes,
            }
        )

    csv_path = OUTPUT_DIR / f"n0q_q_{label}_units.csv"
    write_csv_rows(csv_path, csv_rows)

    true_pos = comparison["true_positives"]
    false_pos = comparison["false_positives"]
    missed = comparison["missed_theoretical_units"]

    json_data = {
        "object": "N0[q]^bullet",
        "q": fraction_to_str(q),
        "parameters": {
            "max_degree": MAX_DEGREE,
            "max_coeff": MAX_COEFF,
            "max_abs_unit_exponent": MAX_ABS_UNIT_EXPONENT,
        },
        "bounded_warning": BOUNDED_WARNING,
        "summary": {
            "total_nonzero_sample_elements": len(nonzero_sample),
            "sample_unit_count": len(sample_units),
            "theoretical_unit_count_within_bound": len(theoretical_in_pos),
            "true_positive_count": len(true_pos),
            "false_positive_count": len(false_pos),
            "missed_theoretical_unit_count": len(missed),
        },
        "sample_units": sorted(
            [fraction_to_str(x) for x in sample_units],
            key=lambda s: float(Fraction(s)),
        ),
        "theoretical_units_within_bound": sorted(
            [fraction_to_str(x) for x in theoretical_in_pos],
            key=lambda s: float(Fraction(s)),
        ),
        "false_positives": sorted(
            [fraction_to_str(x) for x in false_pos],
            key=lambda s: float(Fraction(s)),
        ),
        "missed_theoretical_units": sorted(
            [fraction_to_str(x) for x in missed],
            key=lambda s: float(Fraction(s)),
        ),
    }

    json_path = OUTPUT_DIR / f"n0q_q_{label}_units.json"
    write_json(json_path, json_data)

    interp = _interpretation(
        q,
        len(sample_units),
        len(theoretical_in_pos),
        len(true_pos),
        len(false_pos),
        len(missed),
    )

    return {
        "q": fraction_to_str(q),
        "nonzero_sample_elements": len(nonzero_sample),
        "sample_units": len(sample_units),
        "theoretical_units_within_bound": len(theoretical_in_pos),
        "true_positives": len(true_pos),
        "false_positives": len(false_pos),
        "missed_theoretical_units": len(missed),
        "interpretation": interp,
    }


def build_summary_markdown(results: list[dict[str, object]]) -> None:
    sections: list[str] = []

    sections.append(
        "## Purpose\n\n"
        r"This experiment detects units inside bounded samples of $(\mathbb{N}_0[q]\setminus\{0\}, \cdot)$ "
        "by checking whether multiplicative inverses are also present in the generated sample. "
        "An element $x$ is a **sample unit** if $1/x$ also appears in the same bounded sample. "
        "Results are compared against the theoretical unit structure from Exercise 1.7 (Resource 1)."
    )

    sections.append(
        "## Bounded Warning\n\n"
        "> **" + BOUNDED_WARNING + "**\n\n"
        "Bounded samples can miss units whose inverses require elements outside the generated "
        "sample (false negatives). False positives are rare but possible if the inverse appears "
        "in the sample by coincidence for a theoretically non-unit element."
    )

    sections.append(
        "## Parameters\n\n"
        f"- `max_degree = {MAX_DEGREE}`\n"
        f"- `max_coeff = {MAX_COEFF}`\n"
        f"- `max_abs_unit_exponent = {MAX_ABS_UNIT_EXPONENT}`\n"
        "- Sample generated by `generate_n0_q(q, max_degree, max_coeff)` from `semirings.py`\n"
        "- q values tested: " + ", ".join(r["q"] for r in results)
    )

    table_rows = [
        "| q | Nonzero sample elements | Sample units | Theoretical units (bound) "
        "| True pos. | False pos. | Missed | Interpretation |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for res in results:
        case = res["q"]
        q_frac = Fraction(res["q"])
        a, b = q_frac.numerator, q_frac.denominator
        if b == 1:
            interp_short = f"q={case}: UFM baseline; only unit is 1."
        elif a == 1:
            interp_short = f"q={case}: reciprocal integer; units generated by prime factors of {b}."
        else:
            interp_short = f"q={case}: mixed fraction; theory (Ex. 1.7) predicts only unit 1."
        table_rows.append(
            f"| {res['q']} | {res['nonzero_sample_elements']} | {res['sample_units']} "
            f"| {res['theoretical_units_within_bound']} | {res['true_positives']} "
            f"| {res['false_positives']} | {res['missed_theoretical_units']} "
            f"| {interp_short} |"
        )
    sections.append("## Results Table\n\n" + "\n".join(table_rows))

    sections.append(
        "## Interpretation\n\n"
        r"**q ∈ ℕ (q = 2):** Theory predicts the only unit is $1$. "
        r"The bounded sample of $\mathbb{N}_0[2] = \mathbb{N}_0$ confirms this.\n\n"
        r"**q = 1/n:** The unit group of $(\mathbb{N}_0[1/n]\setminus\{0\},\cdot)$ "
        "is generated by the prime factors of $n$. "
        "Bounded samples may miss theoretical units whose inverses exceed the sample range. "
        r"For $q=1/2$, units include $2$ and $1/2$; for $q=1/6$, units include $2, 3, 1/2, 1/3$, "
        "and their products within the degree bound.\n\n"
        r"**q = a/b with a, b > 1:** Theory (Exercise 1.7) states the only multiplicative "
        r"unit of $(\mathbb{N}_0[q]\setminus\{0\},\cdot)$ is $1$. "
        "The bounded sample confirms this.\n\n"
        "**Unit detection is a prerequisite for studying associates and IDF.** "
        "Two elements are associates if they differ by a unit factor. "
        "Without knowing the unit group, associate classes and length sets cannot be classified."
    )

    sections.append(
        "## Next Experiments\n\n"
        "- `exp_003_group_associate_classes.py` — group elements by associate classes.\n"
        "- `exp_008_valuation_patterns.py` — analyze valuation patterns across the sample.\n"
        "- `exp_007_idf_sanity_checks.py` — IDF sanity checks."
    )

    write_markdown_summary(
        OUTPUT_DIR / "summary.md",
        "Experiment 002 — Bounded Unit Detection",
        sections,
    )


def main() -> None:
    ensure_dir(OUTPUT_DIR)

    results: list[dict[str, object]] = []
    for _, q in N0Q_CASES:
        result = run_case(q)
        results.append(result)

    build_summary_markdown(results)

    csv_files = list(OUTPUT_DIR.glob("*.csv"))
    json_files = list(OUTPUT_DIR.glob("*.json"))
    summary_exists = (OUTPUT_DIR / "summary.md").exists()

    print("")
    print("Experiment 002 complete.")
    print(f"  Output directory      : {OUTPUT_DIR}")
    print(f"  N0[q]^bullet cases    : {len(results)}")
    print(f"  CSV files             : {len(csv_files)}")
    print(f"  JSON files            : {len(json_files)}")
    print(f"  summary.md            : {'yes' if summary_exists else 'MISSING'}")
    print(f"  Proof files mod       : not checked by script")
    print("")
    print("  WARNING: This is bounded computational evidence only.")
    print("  Unit detection is sample-based and does not prove the full unit group.")
    print("")


if __name__ == "__main__":
    main()
